#!/usr/bin/env node
/**
 * Generate infra/db/bootstrap/bootstrap_municipal_services.sql for all 17 municipal
 * Sec5 services (16 Sec5 + shop reference). Idempotent: safe to re-run.
 *
 * Usage: node scripts/dev/generate-municipal-bootstrap.mjs > infra/db/bootstrap/bootstrap_municipal_services.sql
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "../..");
const OUT = path.join(ROOT, "infra/db/bootstrap/bootstrap_municipal_services.sql");

const SERVICES = [
  "shop-service",
  "trade-service",
  "building-service",
  "fire-service",
  "advertisement-service",
  "vendor-service",
  "roadcut-service",
  "event-service",
  "refund-service",
  "sewerage-service",
  "swm-service",
  "drainage-service",
  "parks-service",
  "animal-service",
  "crematorium-service",
  "parking-service",
  "market-service",
];

function meta(serviceDir) {
  const short = serviceDir.replace("-service", "");
  const role = short.replace(/-/g, "_") + "_svc";
  const db = "civitas_" + short.replace(/-/g, "_");
  const pw = role.replace(/_svc$/, "_dev_pw");
  return { short, role, db, pw };
}

const lines = [
  "-- Municipal Sec5 service databases + login roles (17 services).",
  "-- AUTO-GENERATED by scripts/dev/generate-municipal-bootstrap.mjs — re-run to refresh.",
  "-- Idempotent: safe to re-run. Run as Postgres superuser / civitas against postgres db.",
  "-- Migrations (0001_init.sql) create module schemas; this file only provisions L1.",
  "",
];

for (const svc of SERVICES) {
  const { short, role, db, pw } = meta(svc);
  lines.push(`-- ── ${short} (${svc}) ──`);
  lines.push("DO $$ BEGIN");
  lines.push(`  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${role}') THEN`);
  lines.push(`    CREATE ROLE ${role} WITH LOGIN PASSWORD '${pw}' NOSUPERUSER NOCREATEDB NOBYPASSRLS;`);
  lines.push("  END IF;");
  lines.push("END $$;");
  lines.push(`SELECT 'CREATE DATABASE ${db} OWNER ${role}'`);
  lines.push(`  WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '${db}') \\gexec`);
  lines.push(`REVOKE ALL ON DATABASE ${db} FROM PUBLIC;`);
  lines.push(`GRANT CONNECT ON DATABASE ${db} TO ${role};`);
  lines.push("");
}

fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`Wrote ${OUT} (${SERVICES.length} services)`);
