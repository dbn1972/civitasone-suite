#!/usr/bin/env node
/**
 * Extracts route definitions from all services and generates OpenAPI 3.1 YAML.
 * Run: node scripts/docs/generate-openapi.mjs > docs/api/openapi-generated.yaml
 *
 * Scans services/{name}/src/modules/ for Fastify route files matching:
 * routes.ts, *-routes.ts, *.routes.ts, and *-route.ts patterns.
 * Outputs a complete OpenAPI 3.1 document with tags per service and paths
 * grouped by tag.
 */

import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const ROOT = join(__dirname, "..", "..");
const SERVICES_DIR = join(ROOT, "services");

// HTTP methods we extract
const METHODS = ["get", "post", "put", "patch", "delete"];
const ROUTE_REGEX = new RegExp(
  `app\\.(${METHODS.join("|")})\\s*\\(\\s*["'\`]([^"'\`]+)["'\`]`,
  "g"
);

/**
 * Recursively find all route files under a service's src/modules directory.
 * Matches: routes.ts, *-routes.ts, *.routes.ts, *-route.ts
 */
function findRouteFiles(dir) {
  const results = [];
  if (!existsSync(dir)) return results;

  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findRouteFiles(fullPath));
    } else if (entry.name === "routes.ts" || entry.name.endsWith("-routes.ts") || entry.name.endsWith(".routes.ts") || entry.name.endsWith("-route.ts")) {
      results.push(fullPath);
    }
  }
  return results;
}

/**
 * Extract route definitions from a file's content.
 */
function extractRoutes(content) {
  const routes = [];
  let match;
  ROUTE_REGEX.lastIndex = 0;
  while ((match = ROUTE_REGEX.exec(content)) !== null) {
    routes.push({ method: match[1], path: match[2] });
  }
  return routes;
}

/**
 * Convert a path like /v1/finance/budgets/:id to OpenAPI format /v1/finance/budgets/{id}
 */
function toOpenApiPath(path) {
  return path.replace(/:([a-zA-Z_][a-zA-Z0-9_]*)/g, "{$1}");
}

/**
 * Derive a reasonable operationId from method + path.
 */
function toOperationId(method, path) {
  const segments = path
    .replace(/^\/v\d+\//, "")
    .replace(/:([a-zA-Z_]+)/g, "by_$1")
    .split("/")
    .filter(Boolean);
  const prefix = method === "get" ? "list" : method === "post" ? "create" : method;
  return `${prefix}_${segments.join("_")}`.replace(/-/g, "_");
}

// ─── Main ────────────────────────────────────────────────────────────────────

const services = readdirSync(SERVICES_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name.endsWith("-service"))
  .map((d) => d.name)
  .sort();

const tags = [];
const paths = {};
let totalRoutes = 0;

for (const serviceName of services) {
  const modulesDir = join(SERVICES_DIR, serviceName, "src", "modules");
  const routeFiles = findRouteFiles(modulesDir);

  if (routeFiles.length === 0) continue;

  const tagName = serviceName.replace(/-service$/, "");
  const tagLabel = tagName.charAt(0).toUpperCase() + tagName.slice(1);
  tags.push({ name: tagLabel, description: `${tagLabel} service endpoints` });

  for (const file of routeFiles) {
    const content = readFileSync(file, "utf-8");
    const routes = extractRoutes(content);

    for (const { method, path } of routes) {
      const oaPath = toOpenApiPath(path);
      if (!paths[oaPath]) paths[oaPath] = {};

      // Skip duplicates (aliases)
      if (paths[oaPath][method]) continue;

      paths[oaPath][method] = {
        tags: [tagLabel],
        operationId: toOperationId(method, path),
        summary: `${method.toUpperCase()} ${path}`,
        responses: {
          ...(method === "get"
            ? { 200: { description: "Success" } }
            : { 202: { description: "Accepted — processing asynchronously" } }),
          400: { description: "Validation error" },
          401: { description: "Unauthorized" },
          403: { description: "Forbidden" },
        },
        security: [{ bearerAuth: [] }],
      };
      totalRoutes++;
    }
  }
}

// ─── YAML Output ─────────────────────────────────────────────────────────────

function indent(str, level) {
  return str
    .split("\n")
    .map((l) => "  ".repeat(level) + l)
    .join("\n");
}

function yamlValue(val) {
  if (typeof val === "string") {
    if (val.includes(":") || val.includes("#") || val.includes("{")) {
      return `"${val.replace(/"/g, '\\"')}"`;
    }
    return val;
  }
  return String(val);
}

let yaml = `openapi: "3.1.0"
info:
  title: CivitasOne Suite API (Auto-Generated)
  version: "0.2.0"
  description: |
    Auto-generated OpenAPI spec from ${totalRoutes} route definitions across ${tags.length} services.
    Generated by scripts/docs/generate-openapi.mjs
  contact:
    name: CivitasOne Platform Team
    url: https://civitasone.app/docs/api
  license:
    name: AGPL-3.0
    url: https://www.gnu.org/licenses/agpl-3.0.html
servers:
  - url: https://api.civitasone.app
    description: Production
  - url: http://localhost:8080
    description: Local Development
security:
  - bearerAuth: []
tags:
`;

for (const tag of tags) {
  yaml += `  - name: ${yamlValue(tag.name)}\n`;
  yaml += `    description: ${yamlValue(tag.description)}\n`;
}

yaml += `paths:\n`;

const sortedPaths = Object.keys(paths).sort();
for (const p of sortedPaths) {
  yaml += `  "${p}":\n`;
  for (const method of METHODS) {
    const op = paths[p][method];
    if (!op) continue;
    yaml += `    ${method}:\n`;
    yaml += `      tags:\n`;
    for (const t of op.tags) {
      yaml += `        - ${t}\n`;
    }
    yaml += `      operationId: ${op.operationId}\n`;
    yaml += `      summary: "${op.summary}"\n`;
    yaml += `      responses:\n`;
    for (const [code, resp] of Object.entries(op.responses)) {
      yaml += `        "${code}":\n`;
      yaml += `          description: "${resp.description}"\n`;
    }
    yaml += `      security:\n`;
    yaml += `        - bearerAuth: []\n`;
  }
}

yaml += `components:
  securitySchemes:
    bearerAuth:
      type: http
      scheme: bearer
      bearerFormat: JWT
      description: Keycloak OIDC access token (RS256)
`;

process.stdout.write(yaml);

// Summary to stderr
process.stderr.write(
  `\n✓ Generated OpenAPI spec: ${totalRoutes} endpoints across ${tags.length} services\n`
);
