-- does not allow, so its first insert failed, the whole transaction rolled back and the event dead-lettered
-- (the unit test mocked the DB and never saw it). The consumer is fixed in the same change; this migration
-- puts the rows in at deploy time so existing tenants do not depend on a redelivery.
--
-- Design decision: bill validation stays against the national master (head-of-account codes are CGA-assigned,
-- not tenant-defined); a tenant's own chart of accounts holds the sub-heads under these majors.
-- Additive and idempotent: ON CONFLICT DO NOTHING leaves every existing row (and any description edited by
-- ops) untouched. The table has no RLS (migration 0043), so no tenant GUC is needed.

