/**
 * PAY-PROFILES byte-identity proof, run level (real DB, real consumer).
 *
 * A fixed 11-employee govt-scale tenant (NPS / GPF / EPF, X / Y / Z, LOP, a
 * mid-month joiner, an old-regime employee, an ESI-eligible low earner, a
 * back-dated salary revision that generates retro arrears, a structure
 * earning + deduction, and a consultant the run must skip) is paid for
 * 2026-08 through POST /v1/payroll/runs. Every pre-existing money column the
 * run writes -- slips (incl. the components jsonb), statutory PF / GPF / NPS
 * / ESI / TDS rows, retro-arrear rows, the department register and the run
 * totals -- is dumped and compared with tests/fixtures/
 * pay-profiles-legacy-run-snapshot.json.
 *
 * That snapshot was GENERATED BY THIS SAME FILE RUNNING ON origin/main
 * (before PAY-PROFILES), with PAY_PROFILES_WRITE_SNAPSHOT=1. The file only
 * uses APIs that exist on main, so it can regenerate the snapshot there. The
 * HRMS feed carries no pay profiles (an employee with no approved profile ==
 * govt_scale) and 2026-08 is before any HRA-floor go-live, so PAY-PROFILES
 * must reproduce the legacy run exactly.
 */
