async function waitForRun(runId: string): Promise<void> {
  const deadline = Date.now() + 30_000;
  for (;;) {
    await new Promise((r) => setTimeout(r, 250));
    const rows = (await asTenant((tx) => tx.execute(sql`SELECT status, last_error FROM payroll.payroll_runs WHERE id = ${runId}::uuid`))) as unknown as Array<{ status: string; last_error: string | null }>;
    if (rows[0]?.status === "failed") throw new Error(`run failed: ${rows[0].last_error}`);
    const n = (await asTenant((tx) => tx.execute(sql`SELECT count(*)::int AS n FROM payroll.payroll_register WHERE run_id = ${runId}::uuid`))) as unknown as Array<{ n: number }>;
    if ((n[0]?.n ?? 0) > 0) return;
    if (Date.now() > deadline) throw new Error("run did not complete");
  }
}

/** Every legacy column the run writes, ids/timestamps stripped, deterministically ordered. */
async function dump(runId: string): Promise<Record<string, unknown>> {
  const q = async (s: ReturnType<typeof sql>) => (await asTenant((tx) => tx.execute(s))) as unknown as Array<Record<string, unknown>>;
  const str = (rows: Array<Record<string, unknown>>) => JSON.parse(JSON.stringify(rows, (_k, v) => (typeof v === "bigint" ? v.toString() : v)));
  return str([
    { run: await q(sql`SELECT month, run_type, status, total_gross_minor::text, total_net_minor::text FROM payroll.payroll_runs WHERE id = ${runId}::uuid`) },
    { slips: await q(sql`
      SELECT employee_id, employee_no, basic_minor::text, gross_minor::text, total_deductions_minor::text, net_pay_minor::text,
             components, pf_employee_minor::text, pf_employer_minor::text, gpf_minor::text, nps_employee_minor::text,
             nps_employer_minor::text, esi_minor::text, tds_minor::text, status, currency
      FROM payroll.payroll_slips WHERE run_id = ${runId}::uuid ORDER BY employee_no`) },
    { pf: await q(sql`SELECT employee_id, basic_minor::text, emp_contrib_pct::text, er_contrib_pct::text, emp_contrib_minor::text, er_contrib_minor::text, eps_contrib_minor::text, epf_er_contrib_minor::text, period FROM statutory.payroll_pf WHERE run_id = ${runId}::uuid ORDER BY employee_id`) },
    { gpf: await q(sql`SELECT employee_id, basic_minor::text, contrib_pct::text, emp_contrib_minor::text, period FROM statutory.payroll_gpf WHERE run_id = ${runId}::uuid ORDER BY employee_id`) },
    { nps: await q(sql`SELECT employee_id, basic_minor::text, emp_contrib_minor::text, er_contrib_minor::text, period FROM statutory.payroll_nps WHERE run_id = ${runId}::uuid ORDER BY employee_id`) },
    { esi: await q(sql`SELECT employee_id, gross_minor::text, emp_contrib_minor::text, er_contrib_minor::text, period FROM statutory.payroll_esi WHERE run_id = ${runId}::uuid ORDER BY employee_id`) },
    { tds: await q(sql`SELECT employee_id, annual_basic_minor::text, taxable_minor::text, tds_minor::text, period FROM statutory.payroll_tds WHERE run_id = ${runId}::uuid ORDER BY employee_id`) },
    { arrears: await q(sql`SELECT employee_id, component_code, from_period, to_period, old_amount_minor::text, new_amount_minor::text, difference_minor::text, status, source FROM payroll.payroll_arrears WHERE tenant_id = ${TENANT}::uuid ORDER BY employee_id, from_period, component_code`) },
    { register: await q(sql`SELECT department_id, employee_count, total_gross_minor::text, total_deductions_minor::text, total_net_minor::text, total_pf_minor::text, total_esi_minor::text, total_tds_minor::text, total_pt_minor::text, period FROM payroll.payroll_register WHERE run_id = ${runId}::uuid ORDER BY department_id`) },
  ]);
}

let app: FastifyInstance;

beforeAll(async () => {
  const rawSubscribe = queue.subscribe.bind(queue);
  (queue as unknown as { subscribe: typeof queue.subscribe }).subscribe = ((topic: string, handler: (msg: { tenantId: string }) => Promise<void>) =>
    rawSubscribe(topic, (msg: { tenantId: string }) => runWithTenant(msg.tenantId, () => handler(msg)))) as unknown as typeof queue.subscribe;
  registerPayrollConsumers(queue);
  await queue.start();
  app = await buildApp();
  vi.mocked(fetchPayrollInput).mockImplementation(async () => feed() as unknown as Awaited<ReturnType<typeof fetchPayrollInput>>);
  vi.mocked(fetchEmployeeSummaries).mockImplementation(async () => new Map(EMPLOYEES.map((e) => [empId(e.n), {
    fullName: `Snapshot ${e.n}`, departmentName: e.dept === DEPT_B ? "Dept B" : "Dept A", employeeNo: `SNAP-${String(e.n).padStart(2, "0")}`,
  }])));
  await cleanup();
  await seed();
});

afterAll(async () => {
  await cleanup();
  await app.close();
  await sqlClient.end();
});

describe("PAY-PROFILES: a govt-scale run is byte-identical to origin/main", () => {
  it("reproduces every legacy column of the pre-PAY-PROFILES snapshot", async () => {
    const res = await app.inject({
      method: "POST", url: "/v1/payroll/runs",
      headers: { authorization: `Bearer ${signToken({ sub: ACTOR, tid: TENANT, roles: ["payroll_admin"], sid: "snap" }, SECRET, 3600)}`, "content-type": "application/json" },
      payload: { runNo: "SNAP-2026-08", month: MONTH, structureId: STRUCTURE },
    });
    expect([201, 202]).toContain(res.statusCode);
    const runId: string = res.json().data?.id ?? res.json().id;
    await waitForRun(runId);
    const actual = await dump(runId);
    if (process.env.PAY_PROFILES_WRITE_SNAPSHOT === "1") {
      writeFileSync(SNAPSHOT, `${JSON.stringify(actual, null, 2)}\n`);
    }
    const expected = JSON.parse(readFileSync(SNAPSHOT, "utf8")) as unknown;
    expect(actual).toEqual(expected);
  }, 60_000);
});
